package com.esyback.ecommerce.service;

import com.esyback.ecommerce.config.EmailProperties;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;

import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.time.Instant;

/**
 * Sends mail through Resend (resend.com).
 *
 * <p>{@code POST https://api.resend.com/emails} with a Bearer key and a JSON
 * body of {@code from}, {@code to}, {@code subject}, {@code text} and
 * {@code html}. A 2xx carries the new message's id.
 *
 * <p>Deliberately, as with {@link SmsSender}:
 *
 * <ul>
 *   <li><b>No body in the log.</b> Order mail carries an address and an order
 *       number, which is a customer record; the log records that a send
 *       happened and to which masked address, not what it said.</li>
 *   <li><b>No retry.</b> A failed send returns false and the caller carries on
 *       — an order must not fail because a courtesy email did. Retrying risks
 *       two copies of the same notice.</li>
 *   <li><b>Templates are plain text.</b> The HTML part is generated by escaping
 *       and wrapping that text. An admin editing a message should not be able
 *       to break an email's markup, and a template is not a place to accept
 *       raw HTML from a UI.</li>
 * </ul>
 */
@Service
@RequiredArgsConstructor
@Slf4j
public class EmailSender {

    private static final URI ENDPOINT = URI.create("https://api.resend.com/emails");
    private static final Duration TIMEOUT = Duration.ofSeconds(15);

    private final EmailProperties props;
    private final HttpClient http = HttpClient.newBuilder().connectTimeout(TIMEOUT).build();

    /** Why the last send failed, for the admin integrations screen. */
    private volatile Failure lastFailure;

    public record Failure(String reason, Integer statusCode, Instant at) {}

    public Failure getLastFailure() {
        return lastFailure;
    }

    private boolean fail(String reason, Integer status) {
        lastFailure = new Failure(reason, status, Instant.now());
        return false;
    }

    public boolean isConfigured() {
        return props.isConfigured();
    }

    /** A key exists AND the master switch is on. */
    public boolean isSending() {
        return props.isConfigured() && props.isEnabled();
    }

    /**
     * Sends one message. Returns false on any failure so the caller decides
     * what that means, rather than an exception deciding for it.
     *
     * @param to recipient address
     * @param subject already-rendered subject line
     * @param text already-rendered plain-text body
     */
    public boolean send(String to, String subject, String text) {
        if (!props.isConfigured()) return false;
        if (!props.isEnabled()) {
            log.info("Email suppressed: the master switch is off in admin integrations");
            return false;
        }
        if (!looksLikeAddress(to)) {
            log.warn("Email not sent: \"{}\" is not a usable address", mask(to));
            return fail("The recipient address is not usable", null);
        }
        if (subject == null || subject.isBlank() || text == null || text.isBlank()) {
            log.warn("Email not sent: the template rendered empty");
            return fail("The message template rendered empty", null);
        }
        try {
            String body = "{"
                + "\"from\":" + json(props.getFrom()) + ","
                + "\"to\":[" + json(to) + "],"
                + "\"subject\":" + json(subject) + ","
                + "\"text\":" + json(text) + ","
                + "\"html\":" + json(html(text))
                + "}";
            HttpRequest req = HttpRequest.newBuilder(ENDPOINT)
                .timeout(TIMEOUT)
                .header("Authorization", "Bearer " + props.getApiKey())
                .header("Content-Type", "application/json")
                .POST(HttpRequest.BodyPublishers.ofString(body, StandardCharsets.UTF_8))
                .build();
            HttpResponse<String> res = http.send(req, HttpResponse.BodyHandlers.ofString(StandardCharsets.UTF_8));
            if (res.statusCode() / 100 != 2) {
                // Resend's error body names the cause (unverified domain, bad
                // key, invalid from), and that is exactly what the operator
                // needs, so it is surfaced rather than reduced to a code.
                String reason = reasonFrom(res.body());
                log.warn("Resend refused the message ({}): {}", res.statusCode(), reason);
                return fail(reason == null
                    ? "Resend returned HTTP " + res.statusCode()
                    : reason, res.statusCode());
            }
            lastFailure = null;
            log.info("Email accepted by Resend: from={} to={}", props.getFrom(), mask(to));
            return true;
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            log.warn("Email send interrupted");
            return fail("The send was interrupted", null);
        } catch (Exception e) {
            log.warn("Email send failed: {}", e.getClass().getSimpleName());
            return fail("Could not reach Resend (" + e.getClass().getSimpleName() + ")", null);
        }
    }

    /**
     * Deliberately permissive: one {@code @}, something either side, a dot in
     * the domain. Anything stricter rejects addresses that work, and the
     * provider is the real authority on deliverability.
     */
    public static boolean looksLikeAddress(String to) {
        if (to == null) return false;
        String s = to.trim();
        int at = s.indexOf('@');
        if (at <= 0 || at != s.lastIndexOf('@') || at == s.length() - 1) return false;
        String domain = s.substring(at + 1);
        return domain.contains(".") && !domain.startsWith(".") && !domain.endsWith(".")
            && s.indexOf(' ') < 0;
    }

    /** An address with its local part hidden, for the log. */
    static String mask(String to) {
        if (to == null || to.isBlank()) return "??";
        int at = to.indexOf('@');
        if (at <= 0) return "??";
        String local = to.substring(0, at);
        String keep = local.length() <= 2 ? local.substring(0, 1) : local.substring(0, 2);
        return keep + "***" + to.substring(at);
    }

    /** Pulls Resend's {@code message} out of an error body, without a parser. */
    static String reasonFrom(String body) {
        if (body == null) return null;
        int i = body.indexOf("\"message\"");
        if (i < 0) return null;
        int open = body.indexOf('"', body.indexOf(':', i) + 1);
        if (open < 0) return null;
        StringBuilder sb = new StringBuilder();
        for (int p = open + 1; p < body.length(); p++) {
            char c = body.charAt(p);
            if (c == '\\' && p + 1 < body.length()) {
                sb.append(body.charAt(++p));
                continue;
            }
            if (c == '"') break;
            sb.append(c);
        }
        String out = sb.toString().trim();
        return out.isEmpty() ? null : out;
    }

    /**
     * The plain-text body as minimal HTML: escaped, with blank lines becoming
     * paragraphs. Escaping first is the point — an apostrophe or an ampersand
     * in a shop's own wording must not turn into markup.
     */
    static String html(String text) {
        String escaped = text
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;");
        StringBuilder sb = new StringBuilder(
            "<div style=\"font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;"
                + "font-size:15px;line-height:1.6;color:#111\">");
        for (String para : escaped.split("\\r?\\n\\s*\\r?\\n")) {
            String p = para.trim();
            if (p.isEmpty()) continue;
            sb.append("<p>").append(p.replaceAll("\\r?\\n", "<br>")).append("</p>");
        }
        return sb.append("</div>").toString();
    }

    /** A JSON string literal, escaped. */
    static String json(String s) {
        if (s == null) return "\"\"";
        StringBuilder sb = new StringBuilder("\"");
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            switch (c) {
                case '"' -> sb.append("\\\"");
                case '\\' -> sb.append("\\\\");
                case '\n' -> sb.append("\\n");
                case '\r' -> sb.append("\\r");
                case '\t' -> sb.append("\\t");
                default -> {
                    if (c < 0x20) sb.append(String.format("\\u%04x", (int) c));
                    else sb.append(c);
                }
            }
        }
        return sb.append('"').toString();
    }
}
